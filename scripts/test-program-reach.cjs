const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../lib/program-reach.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const reach = context.exports.programReach;
assert.equal(reach(1146, 1145).percentage.toFixed(1), '100.1');
assert.equal(reach(1146, 1145).ringPercentage, 100);
assert.equal(reach(1146, 1145).excess, 1);
assert.equal(reach(1145, 1145).percentage, 100);
assert.equal(reach(1145, 1145).excess, 0);
assert.equal(reach(50, 100).percentage, 50);
assert.equal(reach(0, 1145).percentage, 0);
assert.equal(reach(-1, 1145).percentage, 0);
assert.equal(reach(NaN, 1145).percentage, 0);
assert.equal(reach(0, 0).percentage, 0);
console.log('Program reach checks passed: overflow is visible, ring is bounded, reference total is preserved.');
